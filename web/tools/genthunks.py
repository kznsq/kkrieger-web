"""Generate web/thunks.inc for the WebAssembly player.

Usage: python3 web/tools/genthunks.py /path/to/fr_public
(a checkout of https://github.com/farbrausch/fr_public, for the class table
in werkkzeug3_kkrieger/werkops.cpp).

The original player calls every operator handler through CallCode, which pushes
an array of 32-bit words onto the x86 stack and calls the function. WebAssembly
checks function signatures on indirect calls, so instead each handler in the
player's table (player_kkrieger/kkrieger_oplist.cpp) gets a wrapper that reads
the words with the types of the handler's prototype and makes a typed call.
Pointers are 32 bits in wasm32, so the word array layout is unchanged.
"""
import glob
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import kfile

PORT = Path(__file__).resolve().parents[2]
WORDS = {"sInt": 1, "sU32": 1, "sS32": 1, "sBool": 1, "sF32": 1, "sInt2": 2, "sF322": 2,
         "sF323": 3, "sF324": 4, "sInt3": 3, "sInt4": 4, "sFSRT": 9}


def handlers():
    src = (PORT / "player_kkrieger" / "kkrieger_oplist.cpp").read_text(encoding="latin-1")
    src = re.sub(r"//[^\n]*", "", src)
    seen, out = set(), []
    for cid, init, exe in re.findall(r"(0x[0-9a-f]+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,", src):
        if cid in seen:
            continue
        seen.add(cid)
        out.append((int(cid, 16), init, exe))
    return out


def prototypes(names):
    protos = {}
    for h in sorted(glob.glob(str(PORT / "*.hpp")) + glob.glob(str(PORT / "materials" / "*.hpp"))):
        t = Path(h).read_text(encoding="latin-1")
        t = re.sub(r"//[^\n]*", "", t)
        t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
        for m in re.finditer(r"([\w\s\*]*?)__stdcall\s+(\w+)\s*\(([^)]*)\)\s*;", t, re.S):
            name = m.group(2)
            if name in names and name not in protos:
                ret = " ".join(m.group(1).split()).replace("class ", "").strip()
                params = []
                for a in [x.strip() for x in " ".join(m.group(3).split()).split(",") if x.strip()]:
                    a = a.split("=")[0].strip().replace("class ", "")
                    if a == "void":
                        continue
                    if "*" in a:
                        stars = a.count("*")
                        base = a.replace("*", " ").split()[0]
                        params.append(base + "*" * stars)
                    else:
                        params.append(a.split()[0])
                protos[name] = (ret, params)
    return protos


def call_args(params):
    args, k = [], 0
    for t in params:
        if t.endswith("**"):                     # variable input list, preceded by its count
            args.append("(%s)(a+%d)" % (t, k))
            k += 1
            break
        if t == "...":
            raise ValueError("varargs")
        if t.endswith("*"):
            args.append("(%s)a[%d]" % (t, k))
            k += 1
        else:
            args.append("W<%s>(a,%d)" % (t, k))
            k += WORDS[t]
    return args


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: genthunks.py /path/to/fr_public")
    kfile.WZ3 = Path(sys.argv[1]) / "werkkzeug3_kkrieger"
    classes = kfile.load_classes()           # calling conventions of the branch's code
    hs = handlers()
    names = {n for _, i, e in hs for n in (i, e)}
    protos = prototypes(names)
    lines = ["// generated by web/tools/genthunks.py - do not edit", ""]
    done = set()
    table = []
    for cid, init, exe in hs:
        for name, kind in ((init, "I"), (exe, "E")):
            if name in done:
                continue
            done.add(name)
            ret, params = protos[name]
            args = ",".join(call_args(params))
            if kind == "I":
                lines.append("static KObject *TI_%s(sU32 *a) { return (KObject *)%s(%s); }" % (name, name, args))
            else:
                lines.append("static void TE_%s(sU32 *a) { %s(%s); }" % (name, name, args))
        c = classes.get(cid)
        conv, pack = (c.convention, c.packing) if c else (0, "")
        table.append("  { 0x%02x, 0x%08x, \"%s\", TI_%s, TE_%s, (void *)%s, (void *)%s },"
                     % (cid, conv, pack, init, exe, init, exe))
    lines += ["", "static const PortThunk PortThunks[] =", "{"] + table + ["  { 0,0,0,0,0,0,0 },", "};", ""]
    (PORT / "web" / "thunks.inc").write_text("\n".join(lines))
    print(len(table), "handler classes,", len(done), "thunks")


if __name__ == "__main__":
    main()
